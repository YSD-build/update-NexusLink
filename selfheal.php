/* ---------- 执行 ---------- */
$report = [];
$changed = 0; $same = 0; $failed = 0;
$backupCount = 0;

foreach ($FILES as $name => $b64) {
    $raw = base64_decode($b64, true);
    if ($raw === false || $raw === '') {
        $report[] = ['file' => $name, 'status' => 'decode_failed'];
        $failed++;
        continue;
    }
    $abs = $ROOT . '/' . $name;

    // 打上版本标记，便于肉眼确认文件已更新。
    // 注意：只对 PHP 文件插注释，JSON 等非 PHP 文件保持原样（否则会破坏语法）。
    if (substr(ltrim($raw), 0, 5) === '<?php') {
        $raw = preg_replace(
            '/^\s*<\?php/',
            "<?php\n/* [selfheal] 已由自助修复脚本覆盖于 " . date('Y-m-d H:i:s') . " */",
            $raw,
            1
        );
    }

    // 已处理过则跳过（幂等）—— 用内容哈希比对，对 JSON 等非 PHP 文件同样有效
    $rawSha = hash('sha256', $raw);
    if (is_file($abs)) {
        $cur = (string) @file_get_contents($abs);
        if (hash('sha256', $cur) === $rawSha) {
            $report[] = ['file' => $name, 'status' => 'already_applied', 'size' => strlen($cur)];
            $same++;
            continue;
        }
        // 备份原文件（备份失败不阻断修复，但会如实报告）
        if ($backupDir !== '' && @copy($abs, $backupDir . '/' . $name)) {
            $backupCount++;
        }
    }

    // 检查父目录可写
    if (!is_writable(dirname($abs))) {
        $report[] = [
            'file' => $name, 'status' => 'dir_not_writable',
            'hint' => '站点根目录不可写。请在宝塔中将网站根目录属主设为 PHP 运行用户（通常 www），权限 755',
        ];
        $failed++;
        continue;
    }

    // 原子写入：临时文件 + rename，失败则回退为直接覆盖
    $tmp = $abs . '.selfheal.tmp';
    $ok  = @file_put_contents($tmp, $raw) !== false;
    if ($ok && !@rename($tmp, $abs)) {
        @unlink($tmp);
        $ok = @file_put_contents($abs, $raw) !== false;
    }
    if ($ok) {
        @chmod($abs, 0644);
        $report[] = ['file' => $name, 'status' => 'updated', 'size' => strlen($raw)];
        $changed++;
    } else {
        $report[] = [
            'file' => $name, 'status' => 'write_failed',
            'hint' => '写入失败，请检查文件权限（应为 644、属主 www）',
        ];
        $failed++;
    }
}

